// Quick interaction check: hover a series row, open the lightbox, scroll the statement. Saves frames to the round folder.
import { chromium } from 'playwright';
const round = process.argv[2] || '2';
const dir = `docs/checklists/award-website-rounds/round-${round}`;
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, colorScheme: 'dark' });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
await page.goto('http://localhost:4321/', { waitUntil: 'networkidle' });
await page.waitForTimeout(2500);
const menu = page.locator('nav[aria-label="Series"]');
await menu.scrollIntoViewIfNeeded();
await page.waitForTimeout(600);
const box = await menu.boundingBox();
await page.mouse.move(box.x + 300, box.y + box.height * 0.38);
await page.waitForTimeout(250);
await page.mouse.move(box.x + 500, box.y + box.height * 0.4, { steps: 8 });
await page.waitForTimeout(900);
await page.screenshot({ path: `${dir}/interact-menu-hover.png` });
const tr = page.locator('section[aria-label="Approach"]');
const tb = await tr.boundingBox();
await page.evaluate((y) => window.scrollTo({ top: y, behavior: 'instant' }), (await page.evaluate(() => window.scrollY)) + tb.y + 700);
await page.waitForTimeout(800);
await page.screenshot({ path: `${dir}/interact-textreveal.png` });
await page.goto('http://localhost:4321/work/coast', { waitUntil: 'networkidle' });
await page.waitForTimeout(1200);
await page.locator('[data-lightbox-item]').nth(1).click();
await page.waitForTimeout(900);
await page.screenshot({ path: `${dir}/interact-lightbox.png` });
await page.keyboard.press('ArrowRight');
await page.waitForTimeout(700);
const cap = await page.locator('[data-lb-caption]').textContent();
await page.keyboard.press('Escape');
await page.waitForTimeout(300);
const open = await page.locator('#lightbox').evaluate((d) => d.open);
// Client-side navigation through the view transition router.
await page.click('a[href="/work/portraits"]');
await page.waitForTimeout(1500);
const h1 = await page.locator('h1').textContent();
await page.screenshot({ path: `${dir}/interact-after-nav.png` });
console.log(JSON.stringify({ lightboxCaptionAfterArrow: cap, lightboxStillOpenAfterEsc: open, h1AfterNav: h1?.trim(), errors }));
await browser.close();
